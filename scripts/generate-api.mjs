import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';
import { format, resolveConfig } from 'prettier';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const lockPath = resolve(projectRoot, 'api-contract.lock.json');
const outputPath = resolve(projectRoot, 'src/lib/api/generated/schema.d.ts');
const defaultSourcePath = resolve(projectRoot, '../wedding-be/openapi/openapi.json');

function parseMode(arguments_) {
  if (arguments_.length === 0) {
    return 'generate';
  }

  if (arguments_.length === 1 && arguments_[0] === '--check') {
    return 'check';
  }

  throw new Error('Usage: node scripts/generate-api.mjs [--check]');
}

function parseLock(contents) {
  const value = JSON.parse(contents);
  const source = value?.source;

  if (
    value?.version !== 1 ||
    typeof source?.repository !== 'string' ||
    typeof source.commit !== 'string' ||
    typeof source.path !== 'string' ||
    typeof source.sha256 !== 'string' ||
    !/^[a-f0-9]{64}$/.test(source.sha256)
  ) {
    throw new Error('api-contract.lock.json is invalid.');
  }

  return source;
}

function renderHeader(source) {
  return `/**
 * Generated by scripts/generate-api.mjs. Do not edit by hand.
 * OpenAPI SHA-256: ${source.sha256}
 * Source: ${source.repository}@${source.commit}:${source.path}
 */

`;
}

async function renderSchema(sourceBytes, source) {
  const nodes = await openapiTS(sourceBytes, {
    alphabetize: true,
    immutable: true,
    silent: true,
  });
  const prettierConfig = await resolveConfig(outputPath);

  return format(`${renderHeader(source)}${astToString(nodes)}`, {
    ...prettierConfig,
    filepath: outputPath,
  });
}

async function main() {
  const mode = parseMode(process.argv.slice(2));
  const sourcePath = resolve(process.env.OPENAPI_SOURCE?.trim() || defaultSourcePath);
  const [lockContents, sourceBytes] = await Promise.all([
    readFile(lockPath, 'utf8'),
    readFile(sourcePath),
  ]);
  const source = parseLock(lockContents);
  const actualDigest = createHash('sha256').update(sourceBytes).digest('hex');

  if (actualDigest !== source.sha256) {
    throw new Error(
      `OpenAPI digest mismatch for ${sourcePath}. Expected ${source.sha256}, received ${actualDigest}.`,
    );
  }

  const generated = await renderSchema(sourceBytes, source);

  if (mode === 'check') {
    let committed;

    try {
      committed = await readFile(outputPath, 'utf8');
    } catch (error) {
      if (error instanceof Error && 'code' in error && error.code === 'ENOENT') {
        throw new Error('Generated API schema is missing. Run npm run api:generate.', {
          cause: error,
        });
      }

      throw error;
    }

    if (committed !== generated) {
      throw new Error('Generated API schema is stale. Run npm run api:generate.');
    }

    console.log(`API schema is current (${source.sha256}).`);
    return;
  }

  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, generated, 'utf8');
  console.log(`Generated API schema from ${source.sha256}.`);
}

await main();
